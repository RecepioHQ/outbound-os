'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCES = [
  ['model', 'src/model.js'],
  ['verification', 'src/verification.js'],
  ['preflight', 'src/preflight.js'],
  ['gates', 'src/gates.js']
];
const OUTPUT = path.join(ROOT, 'docs', 'gate-engine.js');

function build() {
  const definitions = SOURCES.map(([name, relativePath]) => {
    const source = fs.readFileSync(path.join(ROOT, relativePath), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    return `    ${JSON.stringify(name)}: function (module, exports, require) {\n${source}\n    }`;
  }).join(',\n');

  return `/* GENERATED by scripts/build-browser-demo.js from the production gate modules. Do not edit. */
(function (root) {
  'use strict';
  const modules = {
${definitions}
  };
  const cache = Object.create(null);
  function load(id) {
    const name = String(id).replace(/^\\.\\//, '');
    if (!Object.prototype.hasOwnProperty.call(modules, name)) {
      throw new Error('Unsupported browser module: ' + name);
    }
    if (Object.prototype.hasOwnProperty.call(cache, name)) return cache[name].exports;
    const module = { exports: {} };
    cache[name] = module;
    modules[name](module, module.exports, load);
    return module.exports;
  }
  root.OutboundGateEngine = Object.freeze({
    evaluateSendGates: load('gates').evaluateSendGates,
    validateDraft: load('preflight').validateDraft
  });
})(window);
`;
}

function main() {
  const output = build();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') !== output) {
      process.stderr.write('Generated browser gate engine is stale: run node scripts/build-browser-demo.js\n');
      process.exitCode = 1;
    } else {
      process.stdout.write('Browser gate bundle matches source modules.\n');
    }
  } else {
    fs.writeFileSync(OUTPUT, output, 'utf8');
    process.stdout.write('Updated docs/gate-engine.js from production source modules.\n');
  }
}
if (require.main === module) main();
module.exports = { build };
