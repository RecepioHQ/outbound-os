const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { build } = require('../scripts/build-browser-demo');
const { evaluateSendGates } = require('../src/gates');
const { validateDraft } = require('../src/preflight');

const ROOT = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'docs/index.html'), 'utf8');
const bundled = fs.readFileSync(path.join(ROOT, 'docs/gate-engine.js'), 'utf8');

function context(overrides = {}) {
  return {
    buyer: { state: 'READY' },
    evidence: { verified: true, fresh: true, attributable: true },
    contact_route: { suitable: true },
    mailbox_verification: { status: 'valid' },
    duplicate: { duplicate: false },
    personalization: { supported: true },
    preflight: { ok: true },
    commercial_review: { ok: true },
    operational: { deliverability_ok: true, rate_ok: true, cap_ok: true },
    authorization: { approved: true },
    approval: { matches: true },
    ...overrides
  };
}

test('browser engine is generated from actual production source and checked in without drift', () => {
  assert.equal(bundled, build());
  assert.match(bundled, /GENERATED by scripts\/build-browser-demo\.js/);
  assert.ok(!/fetch\(|XMLHttpRequest|WebSocket/.test(bundled), 'unexpected networking primitives in engine');
});

test('browser and Node gate decisions match across representative scenarios', () => {
  const win = {};
  vm.runInNewContext(bundled, { window: win }, { timeout: 2000, filename: 'gate-engine.js' });
  assert.equal(typeof win.OutboundGateEngine.evaluateSendGates, 'function');

  const scenarios = [
    context(),
    context({ mailbox_verification: { status: 'unknown' } }),
    context({ buyer: { state: 'HOLD' } }),
    context({ duplicate: { duplicate: true, kind: 'organization' } }),
    context({ authorization: { approved: false } }),
    context({ approval: { matches: false } }),
    context({ evidence: { verified: false, fresh: true, attributable: true } })
  ];
  for (const scenario of scenarios) {
    const expected = evaluateSendGates(scenario);
    const actual = win.OutboundGateEngine.evaluateSendGates(scenario);
    assert.equal(JSON.stringify(actual), JSON.stringify(expected));
  }
  const draft = { recipient: 'example@example.com', subject: 'Hi', text: 'Hello', claims: ['claim'] };
  assert.equal(
    JSON.stringify(win.OutboundGateEngine.validateDraft(draft, [])),
    JSON.stringify(validateDraft(draft, []))
  );
});

test('web demo is self-contained, network-disabled and clearly marked as simulation', () => {
  assert.match(html, /connect-src 'none'/);
  assert.match(html, /No network requests/);
  assert.match(html, /Simulation, not permission to send/);
  assert.match(html, /id="gate-list"/);
  assert.match(html, /src="\.\/gate-engine\.js"/);
  assert.match(html, /src="\.\/app\.js"/);
  assert.doesNotMatch(html, /https?:\/\/[^" ]+\.(?:js|css)/i);
});
